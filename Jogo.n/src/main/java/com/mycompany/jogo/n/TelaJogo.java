    private void iniciarBotoes(){
        
        for(int i =0; i<3;i++){
            
        
            for (JButton botao : botoesJogo[i]) {
                botao.setIcon(new ImageIcon(FUNDO_BRANCO));
            }
        }
    }
    
    private void jogar(int i, int j){
        if(TelaJogo.jogadorVez == 1){
            this.botoesJogo[i][j].setIcon(new ImageIcon(IMG_X));
            TelaJogo.jogadorVez = 2;
        }
        else if(TelaJogo.jogadorVez == 2){
            this.botoesJogo[i][j].setIcon(new ImageIcon(IMG_O));
            TelaJogo.jogadorVez = 1;
        }
        
        System.out.println(TelaJogo.jogadorVez);
        this.botoesJogo[i][j].revalidate();
        this.botoesJogo[i][j].repaint();
    }

