    private void atualizaBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_atualizaBtnActionPerformed
        // TODO add your handling code here:
        int    id    = (int) idTF.getValue();
        String nome  = nomeTF.getText().trim();
        String login = loginTF.getText().trim();
        String senha = senhaTF.getText().trim();
        if(nome.isEmpty() || login.isEmpty() || senha.isEmpty())
        {
            JOptionPane.showMessageDialog(  null, 
                                            "Todos os campos precisam ser preenchidos",
                                            "Erro",
                                            JOptionPane.ERROR_MESSAGE
            );
            return;
        }
        System.out.println( GerenciamentoJogador.listarJogadores());
        
        if(GerenciamentoJogador.buscarJogador(id) == null){
            JOptionPane.showMessageDialog(  null, 
                                            "Não existe jogador com esse login",
                                            "Erro",
                                            JOptionPane.ERROR_MESSAGE
            );
            return;
        }
        
        GerenciamentoJogador.atualizarJogadorSimples(id, nome, login, senha);
        JOptionPane.showMessageDialog(
                                        null,
                                        nome + " adicionado com sucesso!",
                                        "Sucesso",
                                        JOptionPane.INFORMATION_MESSAGE
                                    );
        

        this.setVisible(false);
    }//GEN-LAST:event_atualizaBtnActionPerformed

    private void idTFStateChanged(javax.swing.event.ChangeEvent evt) {//GEN-FIRST:event_idTFStateChanged
        // TODO add your handling code here:
        
        int    id    = (int) idTF.getValue();
        Jogador jogador = GerenciamentoJogador.buscarJogador(id);
        if(jogador != null){
            nomeTF.setText(jogador.getNome());
            loginTF.setText(jogador.getLogin());
            senhaTF.setText(jogador.getSenha());
        }else{
            nomeTF.setText("");
            loginTF.setText("");
            senhaTF.setText("");
        }
        
    }//GEN-LAST:event_idTFStateChanged

